"""The pipeline-cache control's compute shader is a valid, signed DXBC container.

No shader compiler runs in this repository's builds, so the control embeds a
hand-assembled cs_5_0 shader (`dcl_thread_group 1, 1, 1; ret`). The DXBC
checksum is MD5's compression function with Direct3D's own final block, as
implemented by vkd3d-proton:
https://github.com/HansKristian-Work/vkd3d-proton/blob/71cae091b06571e51446cf2a937f0b04c237c04d/libs/vkd3d-shader/checksum.c#L41-L241
"""

import hashlib
import math
from pathlib import Path
import re
import struct
import unittest

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / "probe/graphics-runtime-control/pipeline-cache-shader.h"

_SHIFTS = [7, 12, 17, 22] * 4 + [5, 9, 14, 20] * 4 + [4, 11, 16, 23] * 4 + [6, 10, 15, 21] * 4
_CONSTANTS = [int(abs(math.sin(i + 1)) * 2**32) & 0xFFFFFFFF for i in range(64)]


def _rotate(value, bits):
    value &= 0xFFFFFFFF
    return ((value << bits) | (value >> (32 - bits))) & 0xFFFFFFFF


def md5_compress(state, data):
    """Applies MD5's compression to whole 64-byte blocks without finalization."""
    assert len(data) % 64 == 0
    a0, b0, c0, d0 = state
    for offset in range(0, len(data), 64):
        words = struct.unpack("<16I", data[offset:offset + 64])
        a, b, c, d = a0, b0, c0, d0
        for i in range(64):
            if i < 16:
                f, g = (b & c) | (~b & d), i
            elif i < 32:
                f, g = (d & b) | (~d & c), (5 * i + 1) % 16
            elif i < 48:
                f, g = b ^ c ^ d, (3 * i + 5) % 16
            else:
                f, g = c ^ (b | ~d & 0xFFFFFFFF), (7 * i) % 16
            f = (f + a + _CONSTANTS[i] + words[g]) & 0xFFFFFFFF
            a, d, c = d, c, b
            b = (b + _rotate(f, _SHIFTS[i])) & 0xFFFFFFFF
        a0, b0, c0, d0 = (a0 + a) & 0xFFFFFFFF, (b0 + b) & 0xFFFFFFFF, (c0 + c) & 0xFFFFFFFF, (d0 + d) & 0xFFFFFFFF
    return a0, b0, c0, d0


MD5_INITIAL = (0x67452301, 0xEFCDAB89, 0x98BADCFE, 0x10325476)


def dxbc_checksum(container):
    data = container[20:]
    bits = len(data) * 8 & 0xFFFFFFFF
    bits2 = (bits >> 2) | 1
    leftover = len(data) % 64
    whole = data[:len(data) - leftover]
    tail = data[len(data) - leftover:]
    if leftover >= 56:
        final = tail + b"\x80" + bytes(64 - leftover - 1)
        final += struct.pack("<I", bits) + bytes(56) + struct.pack("<I", bits2)
    else:
        padding = 64 - leftover - 4
        final = struct.pack("<I", bits) + tail + b"\x80" + bytes(padding - 5) + struct.pack("<I", bits2)
    state = md5_compress(MD5_INITIAL, whole + final)
    return struct.pack("<4I", *state)


def compute_shader():
    """A cs_5_0 shader: dcl_thread_group 1, 1, 1; ret."""
    tokens = [0x00050050, 7, 0x0400009B, 1, 1, 1, 0x0100003E]
    shex = b"SHEX" + struct.pack("<I", 4 * len(tokens)) + struct.pack(f"<{len(tokens)}I", *tokens)
    empty_signature = struct.pack("<II", 0, 8)
    chunks = [b"ISGN" + struct.pack("<I", len(empty_signature)) + empty_signature,
              b"OSGN" + struct.pack("<I", len(empty_signature)) + empty_signature,
              shex]
    header_size = 32 + 4 * len(chunks)
    offsets, position = [], header_size
    for chunk in chunks:
        offsets.append(position)
        position += len(chunk)
    container = bytearray(b"DXBC" + bytes(16) + struct.pack("<III", 1, position, len(chunks))
                          + struct.pack(f"<{len(chunks)}I", *offsets) + b"".join(chunks))
    container[4:20] = dxbc_checksum(bytes(container))
    return bytes(container)


def header_text(blob):
    rows = [", ".join(f"0x{byte:02x}" for byte in blob[i:i + 12]) for i in range(0, len(blob), 12)]
    body = ",\n    ".join(rows)
    return ("/* Generated by tests/test_d3d12_pipeline_control.py: a signed cs_5_0 DXBC\n"
            "   container for `dcl_thread_group 1, 1, 1; ret`. */\n"
            "#pragma once\n\n"
            f"static const unsigned char controlComputeShader[{len(blob)}] = {{\n    {body},\n}};\n")


def embedded_shader():
    text = HEADER.read_text()
    match = re.search(r"controlComputeShader\[(\d+)\] = \{(.*?)\};", text, re.S)
    data = bytes(int(value, 16) for value in re.findall(r"0x([0-9a-f]{2})", match[2]))
    assert len(data) == int(match[1])
    return data


class PipelineControlShaderTest(unittest.TestCase):
    def test_md5_compression_matches_md5(self):
        for message in (b"", b"abc", bytes(range(256)) * 3):
            padded = message + b"\x80" + bytes((55 - len(message)) % 64) + struct.pack("<Q", len(message) * 8)
            digest = struct.pack("<4I", *md5_compress(MD5_INITIAL, padded))
            self.assertEqual(digest, hashlib.md5(message).digest())

    def test_embedded_shader_is_the_generated_signed_container(self):
        blob = embedded_shader()
        self.assertEqual(blob, compute_shader())
        self.assertEqual(HEADER.read_text(), header_text(blob))

    def test_container_structure(self):
        blob = embedded_shader()
        self.assertEqual(blob[:4], b"DXBC")
        version, size, count = struct.unpack_from("<III", blob, 20)
        self.assertEqual((version, size, count), (1, len(blob), 3))
        offsets = struct.unpack_from("<3I", blob, 32)
        names = [blob[offset:offset + 4] for offset in offsets]
        self.assertEqual(names, [b"ISGN", b"OSGN", b"SHEX"])
        shex = offsets[2]
        length = struct.unpack_from("<I", blob, shex + 4)[0]
        tokens = struct.unpack_from(f"<{length // 4}I", blob, shex + 8)
        self.assertEqual(tokens[0] >> 16, 5)  # compute shader
        self.assertEqual(tokens[0] & 0xFF, 0x50)  # shader model 5.0
        self.assertEqual(tokens[1], len(tokens))
        self.assertEqual(dxbc_checksum(blob), blob[4:20])


if __name__ == "__main__":
    unittest.main()
